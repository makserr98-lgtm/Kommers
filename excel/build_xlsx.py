def item(cell, n):
    return f'TRIM(MID(SUBSTITUTE(SUBSTITUTE({cell}," ",""),",",REPT(" ",200)),{(n-1)*200+1},200))'

def check_formula(r, idcol, after_cell, clause_cols, task_rng_ids, task_rng_grp, q_ids, self_rng, extra=''):
    parts = []
    parts.append((f'COUNTIF({self_rng},{idcol}{r})>1', '"⚠ ID повторяется"'))
    for n in range(1, 9):
        it = item(after_cell, n)
        parts.append((f'AND({it}<>"",COUNTIF({task_rng_ids},{it})+COUNTIF({task_rng_grp},{it})=0)', f'"⚠ нет действия «"&{it}&"»"'))
    for col in clause_cols:
        cc = f'{col}{r}'
        qid = f'LEFT(SUBSTITUTE({cc}," ",""),FIND("=",{cc}&"=")-1)'
        parts.append((f'AND({cc}<>"",ISERROR(FIND("=",{cc})))', f'"⚠ в условии нет знака ="'))
        parts.append((f'AND({cc}<>"",COUNTIF({q_ids},{qid})=0)', f'"⚠ нет вопроса «"&{qid}&"»"'))
    if extra: parts.append(extra)
    f = '"ок"'
    for cond, msg in reversed(parts): f = f'IF({cond},{msg},{f})'
    return f'=IF({idcol}{r}="","",{f})'

