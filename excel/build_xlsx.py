def match_f(cl):
    return (f'IF({cl}="",FALSE,SUMPRODUCT(({OQ}={cl.replace("cl","cq") if False else "%CQ%"})*({OMARK}<>"")*'
            f'ISNUMBER(SEARCH(","&{OCODE}&",",","&MID({cl},FIND("=",{cl}&"=")+1,999)&",")))>0)')

def comb(v):
    w0, w1, w2, y0, y1 = v
    return (f'IF(OR({w0}="нет",{w1}="нет",{w2}="нет"),"нет",'
            f'IF(AND(OR({y0}<>"",{y1}<>""),{y0}<>"да",{y1}<>"да",{y0}<>"?",{y1}<>"?"),"нет",'
            f'IF(OR({w0}="?",{w1}="?",{w2}="?",AND({y0}<>"да",{y1}<>"да",OR({y0}="?",{y1}="?"))),"?","да")))')

def ddmm(c):
    return f'DAY({c})&"."&RIGHT("0"&MONTH({c}),2)'

